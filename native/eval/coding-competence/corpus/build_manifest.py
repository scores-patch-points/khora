#!/usr/bin/env python3
"""
build_manifest.py -- turn the fetched checkouts + the local ethos material into
    /private/tmp/claude-501/code-corpus/manifest.json   (per language {train, dev, test} + typed gaps)
    /private/tmp/claude-501/code-corpus/PROVENANCE.md   (repo URL, commit SHA, licence, fetch date, split)

DECLARED RULES (fixed before the first build; nothing here looks at reader scores):
  file filters        bytes <= 200 KiB; strict UTF-8, no NUL; >= 15 lines; not minified (code: any line > 1000 chars or
                      mean line > 200; html/json/markdown/latex/yaml/toml: mean line > 500); no generated header in the
                      first 25 lines (langmap.GENERATED_HEAD_RE); ambiguous extensions (.h .m .v .pl .cl .f/.for) resolved by
                      langmap.resolve_ambiguous, refusals dropped; latex/perl content-sanity refusals dropped
  per (repo, lang)    at most CAP_PER_REPO_LANG = 60 files, in sha1(repo+path) order
  per language        <= 40 MB selected text: if over, every (repo, lang) cap is scaled by cap/total, deterministic
  split               BY REPOSITORY. split = sha256(lower(owner/repo)) mod 4 -> {0,1: train, 2: dev, 3: test}; a repo is in
                      exactly one split. If a language has >= 3 repos but the global bins leave a split empty, the
                      language-local rank rule (sha256(lang:repo) order; last floor(n/4) test, previous floor(n/4) dev, >=1
                      each) is used and each moved repo is flagged split_override. If a language has < 3 repos it is split
                      by TOP-LEVEL DIRECTORY (sha256(repo:topdir) mod 4; if the files span < 3 top dirs, by file path hash)
                      and the language is flagged leakage_risk.
  leakage guard       exact duplicate (sha256) and near-duplicate (>= 80% of a file's normalised lines of length >= 20 occur in
                      an earlier-priority split's files of the same language; priority train > dev > test) files are REMOVED from
                      the lower-priority split (dev/test), never from train, and counted.
  restricted          files from copyleft / own-code / not-on-fetch-list licences (local ethos only) are kept in the manifest
                      with restricted=true; per-split counts are reported with and without them.
"""
import hashlib, json, os, re, sys, datetime, math, tomllib
sys.path.insert(0, os.path.dirname(__file__))
import langmap as L
import inventory_local as INV

BASE = "/private/tmp/claude-501/code-corpus"
RAW = f"{BASE}/raw"
META = f"{RAW}/_meta"
PLAN = f"{BASE}/pool/plan.json"
OUT = f"{BASE}/manifest.json"
PROV = f"{BASE}/PROVENANCE.md"
NEAR_DUP_FRAC = 0.8
NEAR_DUP_MIN_LINE = 20
TAINT_FRAC = 0.10   # declared: >= 10% of licence-checked files in a (repo, language) pair carry a copyleft header -> pair refused
PRIORITY = {"train": 0, "dev": 1, "test": 2}
HTML_GENERATOR = re.compile(r'<meta\s+name=["\']generator|created using sphinx|generated by (javadoc|doxygen|pandoc)', re.I)

def sha256(b): return hashlib.sha256(b).hexdigest()
def x_origin_fetched(lst): return bool(lst) and lst[0]["origin"] == "fetched"

def check_text(lang, data, origin="fetched"):
    """Content-level filters. Returns (text or None, reason or None)."""
    if len(data) > L.SIZE_MAX:
        return None, "too-big"
    if b"\x00" in data:
        return None, "nul-byte"
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return None, "not-utf8"
    lines = text.splitlines()
    if len(lines) < L.LINES_MIN:
        return None, "too-few-lines"
    lens = [len(x) for x in lines]
    mean = sum(lens) / len(lens)
    if lang in L.TEXT_LIKE:
        if mean > L.MEAN_LINE_TEXT:
            return None, "minified-text"
    else:
        if max(lens) > L.MAX_LINE_CODE or mean > L.MEAN_LINE_CODE:
            return None, "minified"
    if origin == "fetched" and L.RESTRICTIVE_HEAD_RE.search("\n".join(lines[:L.HEADER_LICENSE_LINES])):
        return None, "copyleft-or-restricted-header"
    head = "\n".join(lines[:L.GENERATED_HEAD_LINES])
    if L.GENERATED_HEAD_RE.search(head):
        return None, "generated-header"
    if lang == "html" and HTML_GENERATOR.search(text[:4000]):
        return None, "generated-html"
    return text, None

def norm_lines(text):
    out = set()
    for ln in text.splitlines():
        s = " ".join(ln.split())
        if len(s) >= NEAR_DUP_MIN_LINE:
            out.add(hashlib.md5(s.encode("utf-8")).hexdigest()[:12])
    return out

def parses(lang, text):
    if lang == "json":
        try:
            json.loads(text); return True
        except Exception:
            return False
    if lang == "toml":
        try:
            tomllib.loads(text); return True
        except Exception:
            return False
    return None

def collect_fetched(plan, cands, stats):
    repos_meta = {}
    for fn in sorted(os.listdir(META)):
        m = json.load(open(f"{META}/{fn}"))
        repos_meta[m["repo"]] = m
    for name, info in plan["repos"].items():
        m = repos_meta.get(name)
        if not m or m.get("error") or not m.get("license_ok"):
            stats["repos_excluded_license_or_clone"].append({"repo": name, "why": (m or {}).get("error") or f"license:{(m or {}).get('license_text_family')}/{(m or {}).get('github_reported_license')}"})
            continue
        dirn = name.replace("/", "_")
        n_c = sum(1 for l, p in info["pairs"].items() if l == "c")
        counts = (sum(len(p["paths"]) for l, p in info["pairs"].items() if l == "c"),
                  sum(len(p["paths"]) for l, p in info["pairs"].items() if l == "cpp"),
                  sum(len(p["paths"]) for l, p in info["pairs"].items() if l == "objc"))
        for lang, pr in info["pairs"].items():
            for rel in pr["paths"]:
                fp = f"{RAW}/{dirn}/{rel}"
                if not os.path.isfile(fp):
                    stats["missing_on_disk"] += 1
                    continue
                nl, nwhy = L.name_candidates(rel)   # re-apply the name filters (they may have grown since planning)
                if nl is None:
                    stats["dropped"]["name:" + nwhy] = stats["dropped"].get("name:" + nwhy, 0) + 1
                    continue
                data = open(fp, "rb").read()
                cands.setdefault((name, lang), []).append({"rel": rel, "path": fp, "data": data, "origin": "fetched"})
    return repos_meta

def collect_local(cands, repos_local):
    inv = json.load(open(INV.OUT))
    for f in inv:
        e = f["ext"]
        lang = L.EXT.get(e)
        if lang is None:
            continue
        repo = f["repo"]
        repos_local.setdefault(repo, {"license": f["license"], "license_class": f["license_class"], "license_source": f["license_source"]})
        data = open(f["path"], "rb").read()
        cands.setdefault((repo, lang), []).append({"rel": f["file"], "path": f["path"], "data": data, "origin": "ethos-local", "txt_peeled": f["txt_peeled"]})

def main():
    plan = json.load(open(PLAN))
    stats = {"repos_excluded_license_or_clone": [], "missing_on_disk": 0, "dropped": {}, "ambiguity": {}}
    cands = {}
    repos_meta = collect_fetched(plan, cands, stats)
    repos_local = {}
    collect_local(cands, repos_local)
    # unambiguous source counts per repo for .h resolution
    h_counts = {}
    for (repo, lang), lst in cands.items():
        c = h_counts.setdefault(repo, [0, 0, 0])
        if lang == "c": c[0] += sum(1 for x in lst if L.ext_of(x["rel"]) == ".c")
        if lang == "cpp": c[1] += sum(1 for x in lst if L.ext_of(x["rel"]) not in (".hpp", ".hh", ".hxx", ".h++", ".ipp", ".inl", ".tpp"))
        if lang == "objc": c[2] += len(lst)
    # --- file filters, ambiguity resolution, copyleft-taint rule, per-(repo,lang) cap
    entries = {l: [] for l in L.LANGUAGES}  # language -> entries
    def drop(why, repo, rel):
        stats["dropped"][why] = stats["dropped"].get(why, 0) + 1
        ex = stats.setdefault("dropped_examples", {}).setdefault(why, [])
        if len(ex) < 6:
            ex.append(f"{repo}:{rel}")
    def evaluate(repo, lang, x):
        """-> (entry or None, reason or None). Pure per-file filter chain."""
        rel = x["rel"]
        fn = rel[:-4] if x.get("txt_peeled") else rel
        ext = L.ext_of(fn)
        amb = L.EXT.get(ext, "")
        rule = None
        data = x["data"]
        try:
            data.decode("utf-8")
        except UnicodeDecodeError:
            return None, "not-utf8"
        if amb.startswith("@"):
            resolved, rule = L.resolve_ambiguous(amb, data.decode("utf-8"), tuple(h_counts.get(repo, [0, 0, 0])))
            stats["ambiguity"][rule] = stats["ambiguity"].get(rule, 0) + 1
            if resolved is None:
                return None, rule
            if resolved != lang:
                return None, "resolved-to-other-language"
        text, why = check_text(lang, data, x["origin"])
        if why:
            return None, why
        why = L.content_sanity(lang, text, ext)
        if why:
            return None, why
        return {"repo": repo, "rel": rel, "path": x["path"], "origin": x["origin"], "bytes": len(data),
                "lines": len(text.splitlines()), "sha256": sha256(data), "ext": ext, "rule": rule,
                "parses": parses(lang, text), "_text": text, "_hk": L.hash_order_key(repo, rel)}, None
    for (repo, lang), lst in sorted(cands.items()):
        lst.sort(key=lambda x: L.hash_order_key(repo, x["rel"]))
        results = [(x, *evaluate(repo, lang, x)) for x in lst]
        # copyleft-taint rule (declared TAINT_FRAC): a repo that vendors copyleft code usually carries the licence header
        # on only some of the vendored files; if >= TAINT_FRAC of the files that reached the licence check carry a
        # copyleft/source-available header, the whole (repo, language) pair is refused.
        n_lic = sum(1 for x, e, why in results if why == "copyleft-or-restricted-header" or (e is not None))
        n_bad = sum(1 for x, e, why in results if why == "copyleft-or-restricted-header")
        if x_origin_fetched(lst) and n_lic and n_bad / n_lic >= TAINT_FRAC:
            stats.setdefault("tainted_pairs", []).append({"repo": repo, "language": lang, "restricted_header_files": n_bad, "checked": n_lic})
            stats["dropped"]["copyleft-tainted-pair"] = stats["dropped"].get("copyleft-tainted-pair", 0) + len(lst)
            continue
        kept = 0
        for x, e, why in results:
            if why:
                drop(why, repo, x["rel"])
                continue
            if kept >= L.CAP_PER_REPO_LANG:
                continue
            kept += 1
            entries[lang].append(e)
    # --- per-language byte cap
    for lang, lst in entries.items():
        tot = sum(e["bytes"] for e in lst)
        if tot > L.LANG_BYTES_CAP:
            scale = L.LANG_BYTES_CAP / tot
            byrepo = {}
            for e in lst:
                byrepo.setdefault(e["repo"], []).append(e)
            keep = []
            for repo, es in byrepo.items():
                es.sort(key=lambda e: e["_hk"])
                keep += es[:max(15, math.ceil(len(es) * scale))]
            stats.setdefault("byte_cap_applied", {})[lang] = {"before_bytes": tot, "before_files": len(lst), "after_files": len(keep)}
            entries[lang] = keep
    # --- repo metadata and licence classes
    def repo_info(repo):
        if repo in repos_meta:
            m = repos_meta[repo]
            return {"origin": "fetched", "url": m["url"], "commit": m["commit"], "branch": m["branch"], "commit_date": m["commit_date"],
                    "fetched_at": m["fetched_at"], "license": m["github_reported_license"], "license_text_family": m["license_text_family"],
                    "license_files": m["license_files"], "license_class": "permissive", "restricted": False}
        lc = repos_local.get(repo, {})
        cls = lc.get("license_class", "unknown")
        return {"origin": "ethos-local", "url": f"https://github.com/{repo}", "commit": None, "license": lc.get("license"),
                "license_source": lc.get("license_source"), "license_class": cls,
                "restricted": cls not in ("permissive",), "note": "collected copy in ethos/09-source-code; read locally for measurement only"}
    # --- split assignment per language
    manifest_langs = {}
    gaps = []
    for lang in L.LANGUAGES:
        lst = entries[lang]
        repos = sorted({e["repo"] for e in lst})
        info = {"split_rule": None, "leakage_risk": False, "split_overrides": [], "notes": []}
        if not lst:
            gaps.append({"language": lang, "gap": "no-files", "reason": "no file survived selection and filters",
                         "plan_coverage": plan["coverage"].get(lang)})
            manifest_langs[lang] = {"train": [], "dev": [], "test": [], "info": {**info, "split_rule": "none"}}
            continue
        assign = {}
        if len(repos) >= L.MIN_REPOS_FOR_REPO_SPLIT:
            g = {r: L.repo_split(r) for r in repos}
            if {"train", "dev", "test"} <= set(g.values()):
                assign = g
                info["split_rule"] = "repo-hash(global)"
            else:
                order = sorted(repos, key=lambda r: hashlib.sha256(f"{lang}:{r}".encode()).hexdigest())
                n = len(order)
                q = max(1, n // 4)
                test_r, dev_r = set(order[n - q:]), set(order[n - 2 * q:n - q])
                for r in order:
                    assign[r] = "test" if r in test_r else "dev" if r in dev_r else "train"
                info["split_rule"] = "repo-hash(language-local-rank)"
                info["split_overrides"] = [{"repo": r, "global": g[r], "assigned": assign[r]} for r in repos if g[r] != assign[r]]
                info["notes"].append("global repo-hash bins left a split empty; language-local rank rule used")
        else:
            info["split_rule"] = "top-level-directory"
            info["leakage_risk"] = True
        by_split = {"train": [], "dev": [], "test": []}
        if info["split_rule"] == "top-level-directory":
            tops = {(e["repo"], e["rel"].split("/")[0] if "/" in e["rel"] else "") for e in lst}
            use_file = len(tops) < 3
            if use_file:
                info["notes"].append("fewer than 3 top-level directories: split by file-path hash (high leakage risk)")
            for e in lst:
                key = f"{e['repo']}:{e['rel']}" if use_file else f"{e['repo']}:{e['rel'].split('/')[0] if '/' in e['rel'] else ''}"
                b = L.SPLIT_BINS[int(hashlib.sha256(key.encode()).hexdigest()[:8], 16) % 4]
                by_split[b].append(e)
        else:
            for e in lst:
                by_split[assign[e["repo"]]].append(e)
        # --- leakage guard: exact + near duplicates removed from lower-priority splits
        seen_sha = {}
        seen_lines = set()
        removed = {"exact": 0, "near": 0}
        for b in ("train", "dev", "test"):
            keep = []
            for e in sorted(by_split[b], key=lambda e: e["_hk"]):
                if b != "train":
                    if e["sha256"] in seen_sha:
                        removed["exact"] += 1
                        continue
                    nl = norm_lines(e["_text"])
                    if nl and len(nl & seen_lines) / len(nl) >= NEAR_DUP_FRAC:
                        removed["near"] += 1
                        continue
                keep.append(e)
            by_split[b] = keep
            for e in keep:
                seen_sha[e["sha256"]] = b
            # lines of this split become "seen" only for LOWER-priority splits
            for e in keep:
                seen_lines |= norm_lines(e["_text"])
        # train-internal exact dups: harmless; keep
        info["leakage_guard_removed"] = removed
        info["repos"] = {b: sorted({e["repo"] for e in by_split[b]}) for b in by_split}
        out = {}
        for b in ("train", "dev", "test"):
            rows = []
            for e in sorted(by_split[b], key=lambda e: (e["repo"], e["rel"])):
                ri = repo_info(e["repo"])
                rows.append({"path": e["path"], "rel": e["rel"], "repo": e["repo"], "bytes": e["bytes"], "lines": e["lines"],
                             "sha256": e["sha256"], "ext": e["ext"], "origin": e["origin"], "restricted": ri["restricted"],
                             **({"resolution": e["rule"]} if e["rule"] else {}), **({"parses": e["parses"]} if e["parses"] is not None else {})})
            out[b] = rows
        counts = {}
        for b in ("train", "dev", "test"):
            rows = out[b]
            free = [r for r in rows if not r["restricted"]]
            counts[b] = {"files": len(rows), "bytes": sum(r["bytes"] for r in rows), "repos": len({r["repo"] for r in rows}),
                         "files_unrestricted": len(free), "repos_unrestricted": len({r["repo"] for r in free})}
            if counts[b]["files_unrestricted"] < L.MIN_FILES_PER_SPLIT:
                gaps.append({"language": lang, "gap": f"split-short:{b}", "files": counts[b]["files_unrestricted"], "repos": counts[b]["repos_unrestricted"],
                             "target": L.MIN_FILES_PER_SPLIT, "plan_coverage": plan["coverage"].get(lang, {}).get(b)})
        manifest_langs[lang] = {**out, "info": {**info, "counts": counts}}
    TARGET_REPOS = {"train": 4, "dev": 3, "test": 3}
    for lang in L.LANGUAGES:
        d = manifest_langs[lang]
        for b in ("train", "dev", "test"):
            byr = {}
            for r in d[b]:
                if not r["restricted"] and r["origin"] == "fetched":
                    byr[r["repo"]] = byr.get(r["repo"], 0) + 1
            big = [r for r, n in byr.items() if n >= 8]
            if len(big) < TARGET_REPOS[b]:
                gaps.append({"language": lang, "gap": f"low-repo-diversity:{b}", "repos_with_8plus_files": len(big), "target": TARGET_REPOS[b],
                             "reason": "permissive candidate repositories in this split's hash bin exhausted or filtered away (see plan/topup logs)"})
    NOTES = {
        "verilog": "SystemVerilog (.sv .svh) is carried in the verilog family; .v is admitted only if it contains module..endmodule",
        "objc": "Objective-C and Objective-C++ (.m .mm); .m/.h admitted by Objective-C syntax markers; MATLAB .m excluded by the same rule",
        "matlab": "MATLAB/Octave .m files (no Objective-C markers); a .m with neither marker is refused",
        "c": ".h files are assigned by content (C++/ObjC syntax markers) then by the repo's dominant unambiguous source language",
        "cpp": "includes .h files that carry C++ syntax or sit in a C++-dominant repo",
        "javascript": ".js .mjs .cjs .jsx", "typescript": ".ts .mts .cts (declaration files .d.ts excluded)", "tsx": ".tsx only",
        "bash": ".sh/.bash scripts of any POSIX-family shell (no dialect check)", "lean": "Lean 3 and Lean 4 are not distinguished",
        "scheme": ".scm .ss .sld; a file needs >= 2 core Scheme forms (tree-sitter query .scm files are refused); .sls omitted (SaltStack)",
        "perl": ".pm and .pl; a .pl needs Perl syntax markers (Prolog refused)", "fortran": ".f90 .f95 .f03 .f08 and .f/.for with Fortran syntax",
        "commonlisp": ".lisp .lsp .asd and .cl with Lisp forms (OpenCL .cl refused)", "groovy": ".groovy and Gradle build scripts (.gradle)",
        "json": "files may be JSONC (comments); `parses` records strict json.loads success", "toml": "`parses` records tomllib success",
        "yaml": ".yml .yaml (workflow files included)", "markdown": "documentation .md/.markdown (LICENSE/CHANGELOG-type files excluded)",
        "html": "template dialects (.scala.html, .html.erb ...) and generator output (javadoc/doxygen/sphinx/pandoc) excluded",
        "latex": ".tex .sty .cls .ltx with TeX commands", "cobol": ".cob .cbl .cobol .cpy; fixed-format and free-format both present",
        "sql": ".sql (dialects not distinguished)", "css": ".css only (no scss/less); .min.css excluded", "scala": ".scala and .sc (.sc needs Scala declarations)",
        "kotlin": ".kt and .kts", "haskell": ".hs and .lhs", "racket": ".rkt", "solidity": ".sol", "svelte": ".svelte", "vue": ".vue (single-file components)",
    }
    for lang in L.LANGUAGES:
        manifest_langs[lang]["info"]["notes_language"] = NOTES.get(lang)
    all_repos = sorted({r["repo"] for lang in manifest_langs.values() for b in ("train", "dev", "test") for r in lang[b]})
    repos_out = {r: {**repo_info(r), "global_split": L.repo_split(r)} for r in all_repos}
    manifest = {
        "schema": "CodeCorpusManifest@1",
        "generated_at": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "root": BASE,
        "declared": {"SIZE_MAX_BYTES": L.SIZE_MAX, "LINES_MIN": L.LINES_MIN, "CAP_PER_REPO_LANG": L.CAP_PER_REPO_LANG,
                     "LANG_BYTES_CAP": L.LANG_BYTES_CAP, "MIN_FILES_PER_SPLIT": L.MIN_FILES_PER_SPLIT, "SPLIT_BINS": L.SPLIT_BINS,
                     "NEAR_DUP_FRAC": NEAR_DUP_FRAC, "NEAR_DUP_MIN_LINE": NEAR_DUP_MIN_LINE, "MAX_LINE_CODE": L.MAX_LINE_CODE,
                     "MEAN_LINE_CODE": L.MEAN_LINE_CODE, "MEAN_LINE_TEXT": L.MEAN_LINE_TEXT, "QUOTA": L.QUOTA,
                     "split_rule": "BY REPOSITORY: sha256(lower(owner/repo)) mod 4 -> {0,1:train, 2:dev, 3:test}"},
        "repos": repos_out,
        "languages": manifest_langs,
        "gaps": gaps,
        "stats": {k: v for k, v in stats.items()},
    }
    json.dump(manifest, open(OUT, "w"), indent=1)
    summ = {"generated_at": manifest["generated_at"], "languages": {}, "gaps": gaps}
    for lang in L.LANGUAGES:
        d = manifest_langs[lang]
        summ["languages"][lang] = {"split_rule": d["info"]["split_rule"], "leakage_risk": d["info"]["leakage_risk"], "counts": d["info"].get("counts"),
                                   "leakage_guard_removed": d["info"].get("leakage_guard_removed"), "note": d["info"].get("notes_language")}
    json.dump(summ, open(f"{BASE}/summary.json", "w"), indent=1)
    write_provenance(manifest, repos_meta)
    print_summary(manifest)

def print_summary(m):
    print(f"{'language':11s} {'train f/r':>11s} {'dev f/r':>11s} {'test f/r':>11s}  split-rule / flags")
    for lang in L.LANGUAGES:
        d = m["languages"][lang]
        c = d["info"].get("counts")
        if not c:
            print(f"{lang:11s} NO FILES")
            continue
        s = " ".join(f"{c[b]['files_unrestricted']:5d}/{c[b]['repos_unrestricted']:<3d}  " for b in ("train", "dev", "test"))
        flags = d["info"]["split_rule"] + (" LEAKAGE_RISK" if d["info"]["leakage_risk"] else "") + (" OVERRIDES=%d" % len(d["info"]["split_overrides"]) if d["info"]["split_overrides"] else "")
        short = [b for b in ("train", "dev", "test") if c[b]["files_unrestricted"] < L.MIN_FILES_PER_SPLIT]
        print(f"{lang:11s} {s} {flags}" + (f"  SHORT:{','.join(short)}" if short else ""))
    print("\nrepos in manifest:", len(m["repos"]), " gaps:", len(m["gaps"]))
    print("dropped by filter:", json.dumps(m["stats"]["dropped"]))
    print("ambiguity rules:", json.dumps(m["stats"]["ambiguity"]))
    print("excluded repos:", len(m["stats"]["repos_excluded_license_or_clone"]))

def write_provenance(m, repos_meta):
    lines = []
    A = lines.append
    A("# PROVENANCE -- khora polyglot code corpus")
    A("")
    A(f"Generated {m['generated_at']} by `khora/native/eval/coding-competence/corpus/build_manifest.py`. Machine-readable twin: `manifest.json`.")
    A("")
    A("## What this is")
    A("")
    A("Real source files for the 51 target languages, split BY REPOSITORY into train / dev / test for held-out measurement of a ZERO-MODEL reader.")
    A("No model wrote or edited any file in this corpus. Priors are to be built from TRAIN only; DEV is for smoke tests; TEST is used once for the final card.")
    A("")
    A("## Fetch method")

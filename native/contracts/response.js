// contracts/response.js — Response@1 and Consequence@1.
//
// Response records the responder, the encounter, the offered response, the
// actual response when supplied, a source address, disclosure limits and any
// resulting plan revisions. Nonresponse is NOT agreement. A model-generated
// account cannot occupy this contract as another's response — the responder
// must be a distinct being from the Fold that generated the account.
//
// Consequence records observed changes, unresolved effects, unexpected affected
// parties and how observations revise the original forecast. Observation is
// distinguished from attribution of causation.

import { makeValidator, isNonEmptyString, isArrayOf } from "./core.js";

export const RESPONSE_SCHEMA = "Response@1";
export const RESPONSE_VERSION = 1;
export const CONSEQUENCE_SCHEMA = "Consequence@1";
export const CONSEQUENCE_VERSION = 1;

export const validateResponse = makeValidator({
  schema: RESPONSE_SCHEMA,
  version: RESPONSE_VERSION,
  checks: [
    (r) => (isNonEmptyString(r.responder) ? { ok: true } : { ok: false, msg: "responder is required" }),
    (r) => (isNonEmptyString(r.encounter_id) ? { ok: true } : { ok: false, msg: "encounter_id is required" }),
    (r) => (isNonEmptyString(r.offered_response) ? { ok: true } : { ok: false, msg: "offered_response is required" }),
    (r) => {
      // actual_response when supplied must be a string; its absence (nonresponse)
      // must not be recorded as agreement.
      if (r.actual_response !== undefined && typeof r.actual_response !== "string") return { ok: false, msg: "actual_response must be a string when supplied" };
      if (r.actual_response === undefined && r.agreement === true) return { ok: false, msg: "nonresponse is not agreement" };
      return { ok: true };
    },
    (r) => (isNonEmptyString(r.source_address) ? { ok: true } : { ok: false, msg: "source_address is required" }),
    (r) => (isArrayOf(r.disclosure_limits, isNonEmptyString) ? { ok: true } : { ok: false, msg: "disclosure_limits must be an array of strings" }),
    (r) => {
      // A model-generated account cannot occupy the contract as another's
      // response: if the responder is not the fold and the account was
      // generated by the fold, it is not a response from that being.
      if (r.model_generated === true && r.responder !== "the-fold") {
        return { ok: false, msg: "a model-generated account cannot occupy this contract as another's response" };
      }
      return { ok: true };
    },
  ],
});

export const validateConsequence = makeValidator({
  schema: CONSEQUENCE_SCHEMA,
  version: CONSEQUENCE_VERSION,
  checks: [
    (r) => (isNonEmptyString(r.encounter_id) ? { ok: true } : { ok: false, msg: "encounter_id is required" }),
    (r) => (isArrayOf(r.observed_changes, isNonEmptyString) ? { ok: true } : { ok: false, msg: "observed_changes must be an array of strings" }),
    (r) => {
      // Observation is distinguished from attribution of causation: a change
      // may be observed without its cause being asserted.
      if (r.observed_changes.length > 0 && r.attributed_causation !== undefined && !isArrayOf(r.attributed_causation, isNonEmptyString)) {
        return { ok: false, msg: "attributed_causation must be an array of strings when present" };
      }
      return { ok: true };
    },
    (r) => (isArrayOf(r.unresolved_effects, isNonEmptyString) ? { ok: true } : { ok: false, msg: "unresolved_effects must be an array of strings" }),
    (r) => (isArrayOf(r.unexpected_affected, isNonEmptyString) ? { ok: true } : { ok: false, msg: "unexpected_affected must be an array of strings" }),
    (r) => {
      if (r.forecast_revision !== undefined && typeof r.forecast_revision !== "string") return { ok: false, msg: "forecast_revision must be a string when present" };
      return { ok: true };
    },
  ],
});

export const RESPONSE = {
  schema: RESPONSE_SCHEMA,
  version: RESPONSE_VERSION,
  validate: validateResponse,
  describe: "nonresponse is not agreement; a model-generated account cannot occupy the contract as another's response",
};
export const CONSEQUENCE = {
  schema: CONSEQUENCE_SCHEMA,
  version: CONSEQUENCE_VERSION,
  validate: validateConsequence,
  describe: "observation is distinguished from attribution of causation",
};